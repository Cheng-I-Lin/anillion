import type { Answer } from "@/lib/types";
// Names and memberships are manually curated factual references. No copied descriptions or artwork.
// Prominence weights are editorial estimates, NOT observed popularity or player percentages.
type Entry = [
  name: string,
  aliases: string,
  prominence: number,
  groups?: string,
  source?: string,
];
function roster(prefix: string, entries: Entry[]): Answer[] {
  return entries.map(([name, aliases, prominence, groups, source]) => ({
    id: `${prefix}:${name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    name,
    source,
    aliases: aliases.split("|").filter(Boolean),
    prominence,
    groups: groups?.split("|"),
    kind: "character",
    franchiseId: prefix,
  }));
}
